/**
 * Builds the globe's dot cloud once, at author time.
 *
 * `dotted-map` ships land dots in Web Mercator grid space. We invert that
 * projection back to lat/lng so the runtime can re-project the same dots
 * orthographically onto a sphere. Output is a compact base64 Int16 payload
 * (lat/lng at 1/100°) so the client pays ~9KB instead of shipping the whole
 * map library.
 */
import DottedMapPkg from "dotted-map";
import { writeFileSync } from "node:fs";

const DottedMap = DottedMapPkg.default ?? DottedMapPkg;

// Constants recovered from dotted-map's own output (see scripts README note).
const X0 = 59.5;
const X_PER_DEG = 64 / 180;
const Y0 = 36.373066958946424;
const Y_SCALE = 20.385;

const map = new DottedMap({ height: 60, grid: "diagonal" });
const points = map.getPoints();

const values = [];
for (const { x, y } of points) {
  const lng = (x - X0) / X_PER_DEG;
  const mercY = (Y0 - y) / Y_SCALE;
  const lat = (2 * Math.atan(Math.exp(mercY)) - Math.PI / 2) * (180 / Math.PI);

  // Mercator explodes near the poles; drop the unusable fringe.
  if (lat > 84 || lat < -60) continue;
  if (lng < -180 || lng > 180) continue;

  values.push(Math.round(lat * 100), Math.round(lng * 100));
}

const buf = Buffer.alloc(values.length * 2);
values.forEach((v, i) => buf.writeInt16LE(v, i * 2));
const b64 = buf.toString("base64");

writeFileSync(
  "lib/globe-data.ts",
  `/* GENERATED by scripts/gen-globe-data.mjs — do not edit by hand. */\n\n` +
    `/** ${values.length / 2} land dots, packed as Int16 lat/lng pairs at 1/100°. */\n` +
    `export const GLOBE_DOTS_B64 =\n  "${b64}";\n`
);

console.log(`wrote lib/globe-data.ts — ${values.length / 2} dots, ${b64.length} b64 chars`);
